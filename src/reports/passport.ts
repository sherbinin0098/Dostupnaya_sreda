export function zoneCode(
  o,
  groupsList: string[],
  rows
): { code: string; n: number; c: Record<string, number>; cover?: number } {
  const mine = rows.filter(({ v }) => groupsList.includes(v.ru.group));
  if (!mine.length) return { code: "", n: 0, c: {} };
  const c: Record<string, number> = {};
  mine.forEach(({ v }) => {
    const k = kindOf(v.k);
    c[k] = (c[k] || 0) + 1;
  });
  const skip = o.skip || {},
    applicable = allRules().filter(
      r => groupsList.includes(r.group) && hasNorm(r) && !skip[skipKey(o, r.id)]
    ).length;
  const cover = applicable ? mine.length / applicable : 1,
    bad = c.bad || 0,
    good = c.good || 0,
    soft = (c.cond || 0) + (c.old || 0);
  let code;
  if (!bad && !soft && cover >= 0.9) code = "ДП-И (К)";
  else if (!bad || good) code = "ДЧ-И (К)";
  else code = "ВНД (К)";
  return { code, n: mine.length, c, cover };
}
