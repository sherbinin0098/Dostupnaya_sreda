import { ACCESS_IDS, NORMS_VERSION, normText, rnd } from "../core/rules";
import { db } from "../core/storage";
import { fmt } from "../core/util";
import { mapLink } from "../place";
import { exportRows } from "./basic";

export function buildLetter(objId) {
  const o = db.objects.find(x => x.id === objId);
  if (!o) return "";
  const rows = exportRows(objId).filter(({ v }) => ["bad", "bad2", "old", "relax"].includes(v.k)),
    dt = new Date().toLocaleDateString("ru-RU");
  let t = `Кому: [наименование органа или организации]\nОт кого: [ФИО, организация, контакты]\nДата: ${dt}\n\nОБРАЩЕНИЕ\nоб устранении нарушений требований доступности объекта\n\n`;
  t += `Объект: ${o.name}${o.address ? ", " + o.address : ""}${o.geo ? " (" + mapLink(o.geo) + ")" : ""}.\n`;
  t += `Обследование №${rnd(o)} выполнено людьми с инвалидностью по методу «тройственный взгляд»: опыт эксперта на коляске, требования норм и реальные возможности по устранению. Нормы: ${NORMS_VERSION}.\n\n`;
  t += `В ходе обследования выявлены несоответствия требованиям доступности для маломобильных групп населения (ст. 15 Федерального закона от 24.11.1995 № 181-ФЗ «О социальной защите инвалидов в Российской Федерации»; СП 59.13330.2020):\n`;
  if (!rows.length) t += `— несоответствий не выявлено.\n`;
  rows.forEach(({ r, v }, i) => {
    const ru = v.ru;
    t += `${i + 1}. ${ru.name}: фактически ${fmt(r.value)} ${ru.unit}, требуется ${normText(ru)} (${ru.clause}, ${ru.doc}).${r.exp ? " Что это значит на коляске: " + r.exp + "." : ""}${r.fix ? " Предлагаемое решение: " + r.fix + "." : ""}\n`;
  });
  if (rows.some(({ v }) => ACCESS_IDS.has(v.ru.id)))
    t += `\nОтдельно сообщаем: на пути к объекту или к части помещений (вход, парковка, туалет, зона услуг и др.) есть препятствия, которые инвалид на коляске не может преодолеть: ступени без пандуса или подъёмника, отсутствие съезда, этажи без лифта, закрытый подход. Всё, что находится за такими препятствиями, недоступно независимо от размеров помещений, поэтому результаты замеров внутри них носят справочный характер.\n`;
  if (o.bstatus === "old")
    t += `\nЗдание введено до 01.07.2016 и не реконструировалось, поэтому просим принять меры по приспособлению объекта (разумное приспособление) и рассмотреть возможность поэтапного устранения.\n`;
  t += `\nПросим:\n1) рассмотреть обращение и принять меры по устранению выявленных нарушений;\n2) сообщить в письменном виде, какие меры и в какие сроки будут приняты;\n3) при невозможности технических решений — организовать альтернативную форму обслуживания.\n\nПриложения: отчёт с фото; паспорт доступности объекта (проект).\n\n[Подпись] [ФИО] ${dt}\n\nЗначения норм должны быть сверены с действующей редакцией свода правил.\n`;
  return t;
}
